# ============================================
# Type Casting
# ============================================

# Type casting is used to convert one
# data type into another.

name = "Raj Singh"
age = 26
gpa = 3.6
is_student = True

# Display the data types
print(type(name))
print(type(age))
print(type(gpa))
print(type(is_student))

# Convert Float to Integer
gpa = int(gpa)
print(gpa)

# Convert Integer to Float
age = float(age)
print(age)

# Convert Float to String
age = str(age)
print(age)

# Convert String to Boolean
name = bool(name)
print(name)