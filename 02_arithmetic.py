# Arithmetic operations are used to perform 
# mathematical calculations in Python.

num = 10

# Addition
result = num + 1
print(result)

# Subtraction
result = num - 1
print(result)

# Multiplication
result = num * 2
print(result)

# Division
result= num / 2
print(result)

# Floor Division
result = num // 3
print(result)

# Modulus (Remainder)
result = num % 3
print(result)

# Exponent (Power)
result = num ** 2
print(result)